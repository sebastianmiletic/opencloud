create or replace function public.account_is_active()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select auth.uid() is not null and coalesce((
    select access.state = 'active'
    from private.account_access access
    where access.user_id = auth.uid()
  ), true);
$$;
revoke all on function public.account_is_active() from public, anon;
grant execute on function public.account_is_active() to authenticated;

create or replace function public.get_my_access()
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select case
    when auth.uid() is null then jsonb_build_object('state', 'signed_out', 'reason', '', 'isOwner', false)
    else jsonb_build_object(
      'state', coalesce(access.state, 'active'),
      'reason', coalesce(access.reason, ''),
      'isOwner', private.is_dev_owner(auth.uid())
    )
  end
  from (select 1) seed
  left join private.account_access access on access.user_id = auth.uid();
$$;
revoke all on function public.get_my_access() from public, anon;
grant execute on function public.get_my_access() to authenticated;

create or replace function public.heartbeat_installation(
  p_install_id uuid,
  p_app_version text,
  p_platform text,
  p_architecture text
)
returns timestamptz
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_now timestamptz := now();
begin
  if auth.uid() is null or not public.account_is_active() then
    raise exception 'Active account required' using errcode = '42501';
  end if;
  if p_install_id is null then
    raise exception 'Installation ID required' using errcode = '22023';
  end if;
  if exists (
    select 1 from public.app_installations
    where install_id = p_install_id and user_id <> auth.uid()
  ) then
    raise exception 'Installation ID belongs to another account' using errcode = '42501';
  end if;

  insert into public.app_installations(
    install_id, user_id, app_version, platform, architecture, first_seen_at, last_seen_at
  ) values (
    p_install_id,
    auth.uid(),
    left(coalesce(nullif(btrim(p_app_version), ''), 'unknown'), 32),
    left(coalesce(nullif(btrim(p_platform), ''), 'unknown'), 32),
    left(coalesce(nullif(btrim(p_architecture), ''), 'unknown'), 32),
    v_now,
    v_now
  )
  on conflict (install_id) do update set
    user_id = auth.uid(),
    app_version = excluded.app_version,
    platform = excluded.platform,
    architecture = excluded.architecture,
    last_seen_at = v_now;

  return v_now;
end;
$$;
revoke all on function public.heartbeat_installation(uuid, text, text, text) from public, anon;
grant execute on function public.heartbeat_installation(uuid, text, text, text) to authenticated;

create or replace function public.dev_summary()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_result jsonb;
begin
  perform private.assert_dev_owner();
  select jsonb_build_object(
    'accounts', (select count(*) from auth.users),
    'installations', (select count(*) from public.app_installations),
    'onlineUsers', (
      select count(distinct user_id)
      from public.app_installations
      where last_seen_at >= now() - interval '2 minutes'
    ),
    'onlineInstallations', (
      select count(*)
      from public.app_installations
      where last_seen_at >= now() - interval '2 minutes'
    ),
    'suspended', (
      select count(*) from private.account_access where state = 'suspended'
    ),
    'generatedAt', now()
  ) into v_result;
  return v_result;
end;
$$;
revoke all on function public.dev_summary() from public, anon;
grant execute on function public.dev_summary() to authenticated;

create or replace function public.dev_list_users(
  p_query text default '',
  p_status text default 'all',
  p_limit integer default 100,
  p_offset integer default 0
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_query text := lower(btrim(coalesce(p_query, '')));
  v_status text := lower(btrim(coalesce(p_status, 'all')));
  v_limit integer := greatest(1, least(coalesce(p_limit, 100), 200));
  v_offset integer := greatest(0, coalesce(p_offset, 0));
  v_result jsonb;
begin
  perform private.assert_dev_owner();
  if v_status not in ('all', 'online', 'offline', 'suspended') then
    raise exception 'Invalid status filter' using errcode = '22023';
  end if;

  with user_rows as (
    select
      users.id,
      coalesce(profiles.username, split_part(users.email, '@', 1), 'User') as username,
      users.email,
      users.created_at as joined_at,
      coalesce(access.state, 'active') as access_state,
      coalesce(access.reason, '') as access_reason,
      private.is_dev_owner(users.id) as is_owner,
      installs.installation_count,
      installs.last_seen_at,
      installs.latest_version,
      installs.latest_platform,
      installs.latest_architecture,
      coalesce(installs.last_seen_at >= now() - interval '2 minutes', false) as is_online
    from auth.users users
    left join public.profiles profiles on profiles.id = users.id
    left join private.account_access access on access.user_id = users.id
    left join lateral (
      select
        count(*)::integer as installation_count,
        max(i.last_seen_at) as last_seen_at,
        (array_agg(i.app_version order by i.last_seen_at desc))[1] as latest_version,
        (array_agg(i.platform order by i.last_seen_at desc))[1] as latest_platform,
        (array_agg(i.architecture order by i.last_seen_at desc))[1] as latest_architecture
      from public.app_installations i
      where i.user_id = users.id
    ) installs on true
    where (
      v_query = ''
      or lower(coalesce(users.email, '')) like '%' || v_query || '%'
      or lower(coalesce(profiles.username, '')) like '%' || v_query || '%'
    )
  ), filtered as (
    select * from user_rows
    where v_status = 'all'
      or (v_status = 'online' and is_online)
      or (v_status = 'offline' and not is_online and access_state <> 'suspended')
      or (v_status = 'suspended' and access_state = 'suspended')
  )
  select jsonb_build_object(
    'total', (select count(*) from filtered),
    'users', coalesce((
      select jsonb_agg(to_jsonb(page) order by page.joined_at desc)
      from (
        select * from filtered
        order by joined_at desc
        limit v_limit offset v_offset
      ) page
    ), '[]'::jsonb)
  ) into v_result;

  return v_result;
end;
$$;
revoke all on function public.dev_list_users(text, text, integer, integer) from public, anon;
grant execute on function public.dev_list_users(text, text, integer, integer) to authenticated;

create or replace function public.dev_user_detail(p_user_id uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_result jsonb;
begin
  perform private.assert_dev_owner();
  if not exists (select 1 from auth.users where id = p_user_id) then
    raise exception 'User not found' using errcode = 'P0002';
  end if;

  select jsonb_build_object(
    'installations', coalesce((
      select jsonb_agg(jsonb_build_object(
        'installId', installs.install_id,
        'appVersion', installs.app_version,
        'platform', installs.platform,
        'architecture', installs.architecture,
        'firstSeenAt', installs.first_seen_at,
        'lastSeenAt', installs.last_seen_at,
        'isOnline', installs.last_seen_at >= now() - interval '2 minutes'
      ) order by installs.last_seen_at desc)
      from public.app_installations installs
      where installs.user_id = p_user_id
    ), '[]'::jsonb),
    'audit', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', audit.id,
        'action', audit.action,
        'reason', audit.reason,
        'createdAt', audit.created_at
      ) order by audit.created_at desc)
      from (
        select * from private.dev_audit_log
        where target_user_id = p_user_id
        order by created_at desc
        limit 50
      ) audit
    ), '[]'::jsonb)
  ) into v_result;
  return v_result;
end;
$$;
revoke all on function public.dev_user_detail(uuid) from public, anon;
grant execute on function public.dev_user_detail(uuid) to authenticated;

create or replace function public.dev_suspend_user(p_user_id uuid, p_reason text default '')
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_reason text := left(btrim(coalesce(p_reason, '')), 500);
  v_audit_id bigint;
begin
  perform private.assert_dev_owner();
  if p_user_id is null or not exists (select 1 from auth.users where id = p_user_id) then
    raise exception 'User not found' using errcode = 'P0002';
  end if;
  if p_user_id = auth.uid() or private.is_dev_owner(p_user_id) then
    raise exception 'The owner account cannot be suspended' using errcode = '42501';
  end if;

  insert into private.account_access(user_id, state, reason, changed_at, changed_by)
  values (p_user_id, 'suspended', v_reason, now(), auth.uid())
  on conflict (user_id) do update set
    state = 'suspended', reason = excluded.reason,
    changed_at = excluded.changed_at, changed_by = excluded.changed_by;

  update public.profiles
  set is_banned = true, ban_reason = v_reason, last_seen_at = null
  where id = p_user_id;

  delete from auth.sessions where user_id = p_user_id;

  insert into private.dev_audit_log(actor_user_id, target_user_id, action, reason)
  values (auth.uid(), p_user_id, 'suspend', v_reason)
  returning id into v_audit_id;

  return jsonb_build_object('userId', p_user_id, 'state', 'suspended', 'auditId', v_audit_id);
end;
$$;
revoke all on function public.dev_suspend_user(uuid, text) from public, anon;
grant execute on function public.dev_suspend_user(uuid, text) to authenticated;

create or replace function public.dev_restore_user(p_user_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_audit_id bigint;
begin
  perform private.assert_dev_owner();
  if p_user_id is null or not exists (select 1 from auth.users where id = p_user_id) then
    raise exception 'User not found' using errcode = 'P0002';
  end if;

  insert into private.account_access(user_id, state, reason, changed_at, changed_by)
  values (p_user_id, 'active', '', now(), auth.uid())
  on conflict (user_id) do update set
