create or replace function private.provision_dev_owner(p_email text)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid;
  v_email text := lower(btrim(p_email));
begin
  select id into v_user_id
  from auth.users
  where lower(email) = v_email
    and email_confirmed_at is not null;

  if v_user_id is null then
    raise exception 'No confirmed Supabase account exists for that email';
  end if;

  insert into private.dev_owners(user_id, expected_email)
  values (v_user_id, v_email)
  on conflict (user_id) do update
    set expected_email = excluded.expected_email;

  delete from private.dev_owners where user_id <> v_user_id;
  return v_user_id;
end;
$$;
revoke all on function private.provision_dev_owner(text) from public, anon, authenticated;

create or replace function private.is_dev_owner(p_user_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from private.dev_owners owners
    join auth.users users on users.id = owners.user_id
    where owners.user_id = p_user_id
      and users.email_confirmed_at is not null
      and lower(users.email) = owners.expected_email
  );
$$;
revoke all on function private.is_dev_owner(uuid) from public, anon, authenticated;

create or replace function private.assert_dev_owner()
